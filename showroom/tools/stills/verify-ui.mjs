function record(name) { results.push(name); console.log('PASS ' + name) }
async function makePage(options = {}, staticMode = false) {
  const context = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 1440, height: 960 }, ...options })
  if (staticMode) await context.addInitScript(() => Object.defineProperty(navigator, 'connection', { value: { saveData: true } }))
  const page = await context.newPage()
  activePage = page
  page.setDefaultTimeout(10000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(url.href)
  await page.waitForSelector(staticMode ? '#load-action' : 'body.live', { timeout: 60000 })
  return page
}
async function screenshot(page, name) { await page.screenshot({ path: fileURLToPath(new URL(name + '.png', output)) }) }
async function audit(page, name) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  assert.deepEqual(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, reason: n.failureSummary })) })), [], name + ' accessibility')
  record(name + ' accessibility')
}
async function navigate(page, id) {
  await page.locator('#track > #' + id).evaluate(element => window.scrollTo(0, element.offsetTop))
  await page.locator('[data-shot="' + id + '"].is-current').waitFor()
}
async function openTool(page, id) {
  const trigger = page.locator('#' + id)
  if (await trigger.getAttribute('aria-expanded') !== 'true') await trigger.click()
  await page.waitForFunction(() => [...document.querySelectorAll('.studio-popover')].some(element => getComputedStyle(element).opacity === '1'))
}
async function choosePaint(page, name) {
  await openTool(page, 'paint-summary')
  await page.locator('#paint-picker label').filter({ hasText: name }).click()
  assert.match(await page.locator('#paint-caption').innerText(), name === '模型原色' ? /青绿/ : new RegExp(name))
}
async function noOverflow(page) {
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow')
  const clipped = await page.locator('.studio-panel:not([hidden]), .studio-popover, #header, .chapter-details, .explorer-details, .wind-dashboard, .loading-focus, .status-notice-content').evaluateAll(elements => elements
    .filter(element => element.getClientRects().length && !element.closest('[inert]'))
    .filter(element => { const r = element.getBoundingClientRect(); return r.left < -1 || r.right > innerWidth + 1 || r.top < -1 || r.bottom > innerHeight + 1 })
    .map(element => element.className))
  assert.deepEqual(clipped, [], 'Panels fit in viewport')
}

