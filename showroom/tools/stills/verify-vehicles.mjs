import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const page = await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error' && !m.text().includes('503')) errors.push(m.text())})
const base=process.argv[2] || 'http://127.0.0.1:5173'
const getState=()=>page.evaluate(async ()=>(await import(performance.getEntriesByType('resource').find(e=>e.name.includes('/src/ui/state.ts')).name)).studioStore.getSnapshot())
const ready=()=>page.waitForSelector('body.live',{timeout:90000})
async function choose(name){await page.locator('#vehicle-picker').click();await page.locator('.studio-popover label').filter({hasText:name}).click();await page.waitForFunction(name=>document.title.startsWith(name),name);await ready()}
try {
 await page.goto(base,{waitUntil:'domcontentloaded'})
 await ready()
 await choose('小米 SU7 Ultra')
 assert.equal((await getState()).vehicleId,'su7-ultra')
 assert.equal(await page.locator('#vehicle-settings').count(),1)
 assert.equal(await page.locator('#door-toggle').count(),0)
 await page.locator('#open-explorer').click()
 await page.locator('#camera-settings').click()
 await page.waitForSelector('.studio-popover')
 assert(await page.getByRole('radio',{name:'第一人称 · 驾驶席',exact:true}).isDisabled())
 await page.keyboard.press('Escape')
 await page.locator('#paint-summary').click()
 await page.locator('#paint-picker label').filter({hasText:'绯红'}).click()
 assert.equal((await getState()).paint,'carmine')
 await page.keyboard.press('Escape')
 await choose('迈凯伦 Ultimate Vision GT')
 assert.equal((await getState()).paint,'original')
 assert.equal((await getState()).exploring,true)
 assert.match(await page.locator('.explorer-heading h2').innerText(),/ULTIMATE VISION GT/)
 await page.locator('#camera-settings').click()
 await page.locator('[data-preset="2"]').click()
 assert.equal((await getState()).selectedPreset,2)
 await page.keyboard.press('Escape')
 await page.locator('#close-explorer').click()
 for(const width of [320,390,768,1440]) {
  await page.setViewportSize({width,height:900})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'overflow '+width)
  const bad=await page.locator('.action-dock, .model-name, #header').evaluateAll(els=>els.filter(e=>{const r=e.getBoundingClientRect();return r.left < -2 || r.right>innerWidth+2}).map(e=>e.className))
  assert.deepEqual(bad,[],'bounds '+width)
  await page.locator('#vehicle-picker').click()
  const box=await page.locator('.studio-popover').boundingBox()
  assert(box.x>=0 && box.x+box.width<=width+1,'picker fits '+width)
  await page.keyboard.press('Escape')
 }
 await page.setViewportSize({width:1440,height:960})
 await page.evaluate(async()=>{const {actions}=await import(performance.getEntriesByType('resource').find(e=>e.name.includes('/src/controller.ts')).name);actions.selectVehicle('su7-ultra');setTimeout(()=>actions.selectVehicle('vision-gt'),30);setTimeout(()=>actions.selectVehicle('mclaren-vgt'),60)})
 await page.waitForTimeout(100)
 await ready()
 assert.equal((await getState()).vehicleId,'mclaren-vgt')
 await choose('小米 Vision GT')
 assert.equal((await getState()).vehicle.cockpit,false)
 await page.locator('#vehicle-settings').click()
 await page.locator('#door-toggle').click()
 assert.equal((await getState()).vehicle.doors,true)
 await page.keyboard.press('Escape')
 await page.route('**/models/su7-ultra.glb*',r=>r.fulfill({status:503,body:'Unavailable'}))
 await page.locator('#vehicle-picker').click()
 await page.locator('.studio-popover label').filter({hasText:'小米 SU7 Ultra'}).click()
 await page.waitForSelector('#load-action')
 assert.equal((await getState()).mode,'static')
 assert.match(await page.locator('#still').getAttribute('src'),/su7-ultra.png/)
 await page.unroute('**/models/su7-ultra.glb*')
 await page.locator('#load-action').click()
 await ready()
 assert.equal((await getState()).vehicle.doors,false)
 assert.deepEqual(errors,[])
 console.log('PASS: UI switching, paint reset, exterior controls, mobile layout, rapid switching, original doors, failure poster and retry; no browser errors')
} finally {await browser.close()}
